#[test]
fn json_carries_the_schema_and_class_objects() {
    let temp = repo(&[("a.rs", "pub fn a() {}\n"), ("n.xyz", "hi\n")]);
    let report = census(temp.path());

    let json = serde_json::to_value(&report).expect("serialize");

    assert_eq!(json["schema"], "loom-census/1");
    assert_eq!(json["totals"]["eligible"]["files"], 1);
    assert_eq!(json["totals"]["eligible"]["bytes"], 14);
    for class in ["excluded", "vendored", "generated", "unsupported"] {
        assert!(json["totals"][class]["bytes"].is_u64(), "totals.{class}");
    }
    let subproject = &json["roots"][0]["subprojects"][0];
    assert_eq!(subproject["by_dialect"]["rust"]["files"], 1);
    assert_eq!(subproject["unsupported_by_extension"]["xyz"]["bytes"], 3);
}

#[test]
fn display_lists_totals_dialects_and_unsupported_extensions() {
    let temp = repo(&[
        ("a.rs", "pub fn a() {}\n"),
        ("vendor/v.rs", "pub fn v() {}\n"),
        ("big.xyz", "0123456789\n"),
        ("small.abc", "x\n"),
    ]);
    let text = census(temp.path()).to_string();

    assert!(text.contains("rust  files 1  bytes 14"), "{text}");
    assert!(text.contains("vendored 1 files 14 bytes"), "{text}");
    assert!(text.contains("excluded roots: .loom"), "{text}");
    let xyz = text.find("xyz  1 files  11 bytes").expect("xyz row");
    let abc = text.find("abc  1 files  2 bytes").expect("abc row");
    assert!(xyz < abc, "largest extension first: {text}");
}

fn long_paths(files: usize) -> Vec<String> {
    let deep: Vec<String> = (0..13)
        .map(|level| format!("d{level:02}{}", "x".repeat(57)))
        .collect();
    let dir = deep.join("/");
    (0..files).map(|n| format!("{dir}/f{n}.rs")).collect()
}

#[test]
fn census_handles_long_paths_beyond_the_argument_limit() {
    const FILES: usize = 32;
    let paths = long_paths(FILES);
    let files: Vec<(&str, &str)> = paths
        .iter()
        .map(|path| (path.as_str(), "pub fn f() {}\n"))
        .collect();
    let temp = repo(&files);

    assert_eq!(census(temp.path()).totals.eligible.files, FILES as u64);

    // Repeating owned fixture paths preserves the argv-size boundary without
    // creating and parsing thousands of identical source files.
    let repeated: Vec<&str> = paths
        .iter()
        .map(String::as_str)
        .cycle()
        .take(3000)
        .collect();
    let total: usize = repeated.iter().map(|path| path.len() + 1).sum();
    assert!(total > 2 * 1024 * 1024, "paths total {total} bytes");
    classify::attributes(temp.path(), &repeated).expect("paths travel through stdin");
}

#[test]
#[ignore = "stress fixture creates and parses 3,000 files; run explicitly"]
