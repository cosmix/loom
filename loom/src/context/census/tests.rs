#[test]
fn a_graph_root_reads_coverage_from_the_graph() {
    let temp = repo(&[
        ("a.rs", "pub fn a() {}\n"),
        ("b.rs", "pub fn b() {}\n"),
        ("c.rs", "pub fn c() {}\n"),
    ]);
    let mut graph = graph_of(temp.path(), &["a.rs", "b.rs"]);
    graph.files.get_mut("b.rs").expect("b.rs").coverage = FileCoverage::ParseError {
        span: Span::default(),
        detail: "boom".to_string(),
    };
    let options = CensusOptions::default();

    let report = run(&options, Some((temp.path(), &graph))).expect("census");

    let root = &report.roots[0];
    let rust = &root.subprojects[0].by_dialect["rust"];
    assert_eq!(root.coverage_source, CoverageSource::Graph);
    assert!(root.parse.is_none());
    assert_eq!(
        (rust.files, rust.symbol_files, rust.parse_errors),
        (3, 1, 1)
    );
    assert_eq!((rust.bytes, rust.symbol_bytes), (42, 14));
    assert_eq!(rust.extractor, "available");
    assert_eq!(counts(root.symbol_level()), (1, 14));
}

