#[test]
fn another_root_is_extracted_in_memory_without_writing() {
    let current = repo(&[("a.rs", "pub fn a() {}\n")]);
    let other = repo(&[("b.rs", "pub fn b() {}\n"), ("c.rs", "pub fn c() {}\n")]);
    let graph = graph_of(current.path(), &["a.rs"]);
    let options = CensusOptions {
        roots: vec![current.path().to_path_buf(), other.path().to_path_buf()],
    };

    let report = run(&options, Some((current.path(), &graph))).expect("census");

    assert_eq!(report.roots[0].coverage_source, CoverageSource::Graph);
    let second = &report.roots[1];
    assert_eq!(second.coverage_source, CoverageSource::InMemory);
    let parse = second.parse.expect("in-memory root reports parse stats");
    assert_eq!((parse.files_parsed, parse.bytes_read), (2, 28));
    assert_eq!(counts(second.symbol_level()), (2, 28));
    assert_eq!(counts(report.totals.eligible), (3, 42));
    assert!(
        !other.path().join(".loom").exists(),
        "a census must not create .loom/ under a root it inspects"
    );
}

