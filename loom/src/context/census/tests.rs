// APFS rejects file names that are not valid UTF-8 (EILSEQ), so the fixture
// cannot exist on macOS.
#[cfg(all(unix, not(target_os = "macos")))]
#[test]
fn a_non_utf8_path_is_counted_once_as_unsupported() {
    use std::ffi::OsStr;
    use std::os::unix::ffi::OsStrExt;

    let temp = repo(&[("a.rs", "pub fn a() {}\n")]);
    let root = temp.path();
    fs::write(
        root.join(OsStr::from_bytes(b"caf\xe9.rs")),
        "pub fn b() {}\n",
    )
    .expect("write");
    git(root, &["add", "-A"]);
    git(root, &["commit", "-q", "-m", "non-utf8"]);

    let report = census(root);
    let totals = &report.totals;

    assert_eq!(counts(totals.eligible), (1, 14));
    assert_eq!(counts(totals.unsupported), (1, 14));
    let file_count = totals.eligible.files
        + totals.excluded.files
        + totals.vendored.files
        + totals.generated.files
        + totals.unsupported.files;
    assert_eq!(file_count, 2, "every tracked file is counted");
    let by_extension = &report.roots[0].subprojects[0].unsupported_by_extension;
    assert_eq!(by_extension["(non-utf8)"].files, 1);
}
