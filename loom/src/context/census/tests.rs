pub(super) fn git(root: &Path, args: &[&str]) {
    let output = Command::new("git")
        .args(args)
        .current_dir(root)
        .env("GIT_CONFIG_GLOBAL", root.join(".loom-test-no-global"))
        .env("GIT_CONFIG_SYSTEM", root.join(".loom-test-no-system"))
        .env("GIT_CONFIG_NOSYSTEM", "1")
        .output()
        .expect("spawn git");
    assert!(
        output.status.success(),
        "git {args:?} failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
}

/// A committed repo holding `files`. Nothing is created under `.loom/`.
pub(super) fn repo(files: &[(&str, &str)]) -> TempDir {
    let temp = tempfile::tempdir().expect("tempdir");
    let root = temp.path();
    git(root, &["init", "-q"]);
    git(root, &["config", "user.name", "t"]);
    git(root, &["config", "user.email", "t@t"]);
    for (path, body) in files {
        let full = root.join(path);
        fs::create_dir_all(full.parent().expect("parent")).expect("create dirs");
        fs::write(full, body).expect("write file");
    }
    git(root, &["add", "-A"]);
    git(root, &["commit", "-q", "-m", "seed"]);
    temp
}

pub(super) fn census(root: &Path) -> CensusReport {
    let options = CensusOptions {
        roots: vec![root.to_path_buf()],
    };
    run(&options, None).expect("census")
}

pub(super) fn counts(count: Count) -> (u64, u64) {
    (count.files, count.bytes)
}

/// The resolved graph a build of `paths` under `root` would hold.
fn graph_of(root: &Path, paths: &[&str]) -> ResolvedGraph {
    let extractors = registry();
    let files = paths
        .iter()
        .map(|path| {
            let bytes = fs::read(root.join(path)).expect("read fixture");
            let extraction = extract_file(&extractors, Path::new(path), &bytes);
            (
                path.to_string(),
                FileEntry::from_extraction(&bytes, extraction),
            )
        })
        .collect();
    ResolvedGraph {
        base_revision: String::new(),
        overlaid: BTreeSet::new(),
        files,
    }
}

#[test]
fn classifies_every_class_and_totals_bytes() {
    let temp = repo(&[
        ("src/a.rs", "pub fn a() {}\n"),
        ("vendor/v.rs", "pub fn v() {}\n"),
        ("src/gen.rs", "// @generated\npub fn g() {}\n"),
        ("notes.xyz", "hello\n"),
        ("target/t.rs", "pub fn t() {}\n"),
        ("lib/attr_vendored.rs", "pub fn x() {}\n"),
        ("lib/attr_generated.rs", "pub fn y() {}\n"),
        (
            ".gitattributes",
            "lib/attr_vendored.rs linguist-vendored\nlib/attr_generated.rs linguist-generated\n",
        ),
    ]);
    let report = census(temp.path());

    assert_eq!(counts(report.totals.eligible), (1, 14));
    assert_eq!(counts(report.totals.vendored), (2, 28));
    assert_eq!(counts(report.totals.generated), (2, 42));
    assert_eq!(counts(report.totals.excluded), (1, 14));
    // notes.xyz and .gitattributes.
    assert_eq!(report.totals.unsupported.files, 2);
    assert_eq!(report.totals, report.roots[0].totals);
}

#[test]
fn every_generated_marker_is_found_only_in_the_first_kilobyte() {
    let late = format!("{}\n// @generated\n", "x".repeat(1100));
    let temp = repo(&[
        ("a.rs", "// @generated\n"),
        ("b.rs", "// DO NOT EDIT\n"),
        ("c.go", "// Code generated by tool.\n"),
        ("d.py", "# autogenerated\n"),
        ("e.rs", late.as_str()),
    ]);
    let report = census(temp.path());

    assert_eq!(report.totals.generated.files, 4);
    assert_eq!(
        report.totals.eligible.files, 1,
        "e.rs marks past 1024 bytes"
    );
}

