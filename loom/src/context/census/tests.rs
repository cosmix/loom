#[test]
fn groups_files_by_nearest_manifest() {
    let temp = repo(&[
        ("Cargo.toml", ""),
        ("src/a.rs", "pub fn a() {}\n"),
        ("web/package.json", "{}\n"),
        ("web/app.ts", "export const a = 1;\n"),
        ("web/deep/b.ts", "export const b = 2;\n"),
        ("crates/core/Cargo.toml", ""),
        ("crates/core/src/l.rs", "pub fn l() {}\n"),
    ]);
    let report = census(temp.path());
    let by_path: BTreeMap<&str, &SubprojectCensus> = report.roots[0]
        .subprojects
        .iter()
        .map(|subproject| (subproject.path.as_str(), subproject))
        .collect();

    assert_eq!(
        by_path.keys().copied().collect::<Vec<_>>(),
        vec![".", "crates/core", "web"]
    );
    assert_eq!(by_path["web"].by_dialect["typescript"].files, 2);
    assert_eq!(by_path["crates/core"].by_dialect["rust"].files, 1);
    assert_eq!(by_path["."].by_dialect["rust"].files, 1);
}

